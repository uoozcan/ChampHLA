"""
generate_performance_figures.py — Figure 8: Computational performance comparison

Generates a 1×3 panel figure (Peak RAM / CPU utilisation / Wall-clock time)
showing all 8 HLA typing tools × available sequencing modalities (WGS/WES/RNA-seq),
with IQR error bars (P25–P75) from the n=30 benchmark.

Data source:
    analysis/performance_benchmark_n30/tables/timing_summary_n30.tsv
    (generated by bin/parse_nextflow_trace_timing.py)

Usage:
    python3.11 bin/generate_performance_figures.py

Output:
    analysis/figures_final/figure_8_computational_performance.{pdf,svg,png}
    analysis/figures_manuscript/figure_8_computational_performance.{pdf,png}
"""

import csv
import sys
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import matplotlib.patches as mpatches
from pathlib import Path

# ---------------------------------------------------------------------------
# Plot style
# ---------------------------------------------------------------------------
sys.path.insert(0, str(Path(__file__).parent.parent / "figure_hub"))
from plot_style import apply_style, save_fig, WONG, MOD_COLORS

apply_style()

# ---------------------------------------------------------------------------
# Load timing data from TSV
# ---------------------------------------------------------------------------
BASE = Path("/scratch/project_2008084/pihla-publish")
TIMING_TSV = BASE / "analysis" / "performance_benchmark_n30" / "tables" / "timing_summary_n30.tsv"

METRIC_KEY = {
    "Peak RAM (GB)":          ("median_peak_ram_gb",  "p25_peak_ram_gb",  "p75_peak_ram_gb"),
    "CPU utilisation (%)":    ("median_cpu_pct",       "p25_cpu_pct",       "p75_cpu_pct"),
    "Wall-clock time (hours)": ("median_runtime_hours", "p25_runtime_hours", "p75_runtime_hours"),
}

TOOLS = ["OptiType", "ArcasHLA", "HLA-HD", "T1K", "SpecHLA",
         "Kourami", "POLYSOLVER", "Seq2HLA"]

MODALITIES = ["WGS", "WES", "RNA"]

def _float(s):
    try:
        return float(s)
    except (TypeError, ValueError):
        return None

tsv_data: dict[tuple, dict] = {}
if TIMING_TSV.exists():
    with open(TIMING_TSV, newline="") as fh:
        for row in csv.DictReader(fh, delimiter="\t"):
            key = (row["tool"], row["modality"])
            tsv_data[key] = {k: _float(v) for k, v in row.items()}
else:
    print(f"WARNING: timing TSV not found at {TIMING_TSV}", file=sys.stderr)

def get_vals(metric: str, tool: str, modality: str):
    med_col, p25_col, p75_col = METRIC_KEY[metric]
    row = tsv_data.get((tool, modality))
    if row is None:
        return None, None, None
    return row.get(med_col), row.get(p25_col), row.get(p75_col)

def get_n(tool: str, modality: str) -> int | None:
    row = tsv_data.get((tool, modality))
    if row is None:
        return None
    n = row.get("n_samples")
    return int(n) if n is not None else None

# ---------------------------------------------------------------------------
# Axis limits — compute from actual data with padding
# ---------------------------------------------------------------------------
def compute_ylim(metric: str, pad_frac: float = 0.15):
    all_vals = []
    for tool in TOOLS:
        for mod in MODALITIES:
            med, _, p75 = get_vals(metric, tool, mod)
            if p75 is not None:
                all_vals.append(p75)
            elif med is not None:
                all_vals.append(med)
    if not all_vals:
        return (0, 1)
    mx = max(all_vals)
    return (0, round(mx * (1 + pad_frac) + 0.5, 0))

METRIC_YLIMS = {
    metric: compute_ylim(metric)
    for metric in METRIC_KEY
}
METRIC_YLIMS["Peak RAM (GB)"]          = (0, max(METRIC_YLIMS["Peak RAM (GB)"][1], 16))
METRIC_YLIMS["CPU utilisation (%)"]    = (0, max(METRIC_YLIMS["CPU utilisation (%)"][1], 900))
METRIC_YLIMS["Wall-clock time (hours)"] = (0, max(METRIC_YLIMS["Wall-clock time (hours)"][1], 3))

# ---------------------------------------------------------------------------
# Colours and layout
# ---------------------------------------------------------------------------
MOD_PALETTE = {
    "WGS": WONG["orange"],
    "WES": WONG["blue"],
    "RNA": WONG["green"],
}

BAR_WIDTH = 0.22
N_TOOLS   = len(TOOLS)
X_POS     = np.arange(N_TOOLS)
OFFSETS   = [-BAR_WIDTH, 0, BAR_WIDTH]

# ---------------------------------------------------------------------------
# Figure — 1×3 layout
# ---------------------------------------------------------------------------
fig, axes = plt.subplots(
    nrows=1, ncols=3,
    figsize=(14, 4.5),
    sharex=True,
)
fig.patch.set_facecolor("#f8f6f0")

METRICS = ["Peak RAM (GB)", "CPU utilisation (%)", "Wall-clock time (hours)"]

for col_idx, metric in enumerate(METRICS):
    ax = axes[col_idx]
    ylim = METRIC_YLIMS[metric]

    for mod_idx, mod in enumerate(MODALITIES):
        bar_x = X_POS + OFFSETS[mod_idx]

        for b_idx, tool in enumerate(TOOLS):
            med, p25, p75 = get_vals(metric, tool, mod)

            if med is None:
                ax.bar(
                    bar_x[b_idx],
                    ylim[1] * 0.04,
                    width=BAR_WIDTH * 0.90,
                    color="#d1d5db",
                    edgecolor="#9ca3af",
                    linewidth=0.5,
                    hatch="////",
                    zorder=3,
                )
            else:
                if p25 is not None and p75 is not None:
                    yerr_lo = max(0, med - p25)
                    yerr_hi = max(0, p75 - med)
                    yerr = [[yerr_lo], [yerr_hi]]
                else:
                    yerr = None

                ax.bar(
                    bar_x[b_idx],
                    med,
                    width=BAR_WIDTH * 0.90,
                    color=MOD_PALETTE[mod],
                    alpha=0.82,
                    edgecolor="white",
                    linewidth=0.4,
                    zorder=3,
                    label=mod if (col_idx == 0 and b_idx == 0) else "_nolegend_",
                )
                if yerr is not None:
                    ax.errorbar(
                        bar_x[b_idx],
                        med,
                        yerr=yerr,
                        fmt="none",
                        ecolor="#374151",
                        elinewidth=0.8,
                        capsize=2,
                        capthick=0.8,
                        zorder=4,
                    )

    ax.set_ylim(ylim)
    ax.set_xlim(-0.6, N_TOOLS - 0.4)
    ax.set_xticks(X_POS)
    ax.set_xticklabels(TOOLS, rotation=40, ha="right", fontsize=7.5)
    ax.tick_params(axis="y", labelsize=7.5)
    ax.set_facecolor("#ffffff")
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.grid(axis="y", alpha=0.28, color="#d7dde5", zorder=0)
    ax.set_axisbelow(True)
    ax.set_title(metric, fontsize=10, fontweight="bold", pad=8)

    letter = chr(65 + col_idx)
    ax.text(
        0.01, 0.97, letter,
        transform=ax.transAxes,
        fontsize=9, fontweight="bold",
        va="top", ha="left", color="#1e293b",
    )

# ---------------------------------------------------------------------------
# Shared legend
# ---------------------------------------------------------------------------
legend_patches = [
    mpatches.Patch(color=MOD_PALETTE[m], label=m, alpha=0.82) for m in MODALITIES
]
legend_patches.append(
    mpatches.Patch(facecolor="#d1d5db", edgecolor="#9ca3af", hatch="////",
                   label="N/A")
)
fig.legend(
    handles=legend_patches,
    loc="center right",
    bbox_to_anchor=(0.995, 0.5),
    fontsize=8,
    title="Modality",
    title_fontsize=8,
    frameon=True,
    framealpha=0.95,
    edgecolor="#d8dee9",
    borderpad=0.7,
)

# ---------------------------------------------------------------------------
# Title and footnote
# ---------------------------------------------------------------------------
n_notes = []
for mod in MODALITIES:
    ns = {get_n(t, mod) for t in TOOLS if get_n(t, mod) is not None}
    if len(ns) == 1:
        n_notes.append(f"{mod} n={ns.pop()}")
    elif ns:
        n_notes.append(f"{mod} n={min(ns)}–{max(ns)}")
mod_notes = "; ".join(n_notes)

fig.suptitle(
    "Figure 8 — Computational resource requirements per HLA typing tool\n"
    "across sequencing modalities (WGS / WES / RNA-seq)",
    fontsize=11,
    fontweight="bold",
    y=1.01,
)

fig.text(
    0.01, 0.01,
    f"Measured via Nextflow execution trace (realtime, peak_rss, %cpu) on 1000G benchmark samples ({mod_notes}).\n"
    "Bars show median; error whiskers show P25–P75 interquartile range. Hatch = tool not applicable to modality.",
    fontsize=6.5,
    color="#64748b",
    ha="left",
    va="bottom",
)

plt.tight_layout(rect=(0.0, 0.06, 0.90, 0.95))

# ---------------------------------------------------------------------------
# Save
# ---------------------------------------------------------------------------
out_final = BASE / "analysis" / "figures_final" / "figure_8_computational_performance"
out_manuscript = BASE / "analysis" / "figures_manuscript" / "figure_8_computational_performance"

for stem in [out_final, out_manuscript]:
    stem.parent.mkdir(parents=True, exist_ok=True)

save_fig(fig, out_final, dpi=300, formats=("pdf", "svg", "png"), close=False)
save_fig(fig, out_manuscript, dpi=300, formats=("pdf", "png"), close=True)

print("Figure 8 saved:")
print(f"  {out_final}.pdf / .svg / .png")
print(f"  {out_manuscript}.pdf / .png")
print(f"  Data: {mod_notes}")
